package org.simplemodeling.textus.smworkflow.admission

import cats.data.NonEmptyVector
import io.circe.Json
import org.goldenport.Consequence
import org.goldenport.cncf.action.{ActionCall, CommandAction, ProcedureActionCall}
import org.goldenport.protocol.Request
import org.goldenport.protocol.operation.{OperationRequest, OperationResponse}
import org.goldenport.protocol.spec as spec
import org.goldenport.record.Record
import org.simplemodeling.textus.smworkflow.value as V

/** Public control projection after native commit. Full material remains in the
  * already retained issued-work owner and is read explicitly, never archived a
  * second time or regenerated by advancing the Workflow.
  * @since   Nov.  8, 2026
  * @version Nov. 11, 2026
  */
private[smworkflow] object NativeWorkflowCompactResponse {
  private val bodies = Set("work", "state", "conflict", "review", "repair", "purposeWork", "partition", "scope",
    "reasoning", "repositoryConflict", "repositoryReview", "repositoryRepair", "validation", "findingRecording", "reviewContext",
    "human", "repositoryHuman", "scopeHuman", "reasoningHuman", "completion", "selectedPlan")

  def summary(record: Record): Record = {
    val selected = record.fields.filter(field => bodies(field.key)).flatMap { field =>
      val json = DevelopmentOperationalView.json(field.value.single)
      val names = Set("kind", "purpose", "stepIdentity", "rationale", "reason", "choices", "judgmentMode", "stage", "generation",
        "repairCount", "repairLimit", "synchronization", "repository", "metrics", "originalBase", "reviewedCandidate",
        "evidenceRecording", "assessmentJournal", "documentEffect", "candidate", "sourceRevision", "scopeIdentity", "outcome", "selectedChecks")
      json.asObject.map(fields => field.key -> GoalPhaseNativeMetadata.record(Json.fromJsonObject(fields.filter {
        case (key, value) => names(key) && !value.isNull
      })))
    }
    Record.createFull(selected)
  }

  private def compact(record: Record, reference: V.WorkflowRetainedWorkReference): Record =
    Record.createFull(record.fields.filterNot(field => bodies(field.key) || Set("retainedWork", "controlSummary")(field.key))
      .map(field => field.key -> field.value.single)) ++
      Record.data("retainedWork" -> reference.toRecord(), "controlSummary" -> summary(record))

  def compactC(record: Record, core: ActionCall.Core): Consequence[Record] =
    if (record.getString("kind").contains("Human") && record.getString("submitOperation").isEmpty &&
        record.getRecord("state").nonEmpty && Option(core.action).flatMap(_.request.service).exists(
          Set("GoalTaskService", "DelegateTaskService", "StandaloneFixService")))
      // A bounded Human stage is retained business state, not an issued native
      // Decision. Its exact checkpoint is selected by response materials below;
      // no completion operation or decision reference may be manufactured.
      Consequence.success(record)
    else if (record.getString("kind").contains("Human"))
      WorkflowRetainedWork.confirmedDecisionC(record, core).map(compact(record, _))
    else if (!record.getString("kind").contains("Request")) Consequence.success(record)
    else record.getAny("issuedWorkContext").collect { case value: Record => value } match {
      case None => Consequence.success(record)
      case Some(value) => for {
        context <- V.WorkflowIssuedWorkContext.createC(value)
        reference <- WorkflowRetainedWork.confirmedC(context, core)
      } yield compact(record, reference)
    }

  def responseC(response: OperationResponse, core: ActionCall.Core): Consequence[OperationResponse] = response match {
    case OperationResponse.RecordResponse(record) => compactC(record, core).flatMap { compacted => for {
      references <- WorkflowResponseMaterials.referencesC(compacted, core)
    } yield if (references.isEmpty) OperationResponse.RecordResponse(compacted) else {
      val fields = references.map(_.fieldName).toSet
      val prior = compacted.getRecord("controlSummary").getOrElse(Record.empty)
      val additional = summary(compacted)
      val combined = Record.createFull(prior.fields.filterNot(field => additional.getAny(field.key).nonEmpty)
        .map(field => field.key -> field.value.single)) ++ additional
      OperationResponse.RecordResponse(Record.createFull(compacted.fields.filterNot(field =>
        fields(field.key) || Set("controlSummary", "retainedMaterials")(field.key)).map(field => field.key -> field.value.single)) ++
        Record.data("controlSummary" -> combined, "retainedMaterials" -> references.map(_.toRecord())))
    } }
    case other => Consequence.success(other)
  }

  /** Wrap external public services, leaving native in-process composition typed.
    * The explicit detail service itself is deliberately never wrapped.
    */
  def bind(service: spec.ServiceDefinition): spec.ServiceDefinition =
    NativeWorkflowDescriptionMetadata.service(service, spec.OperationDefinitionGroup(NonEmptyVector.fromVectorUnsafe(
      service.operations.operations.toVector.map { original => new spec.OperationDefinition {
        val specification = original.specification
        def createOperationRequest(incoming: Request): Consequence[OperationRequest] =
          original.createOperationRequest(incoming).map {
            case command: CommandAction => new CommandAction {
              val request = command.request
              override def commandExecutionMode = command.commandExecutionMode
              def createCall(c: ActionCall.Core): ActionCall = new ProcedureActionCall {
                val core = c
                private val delegate = command.createCall(c.copy(action = command))
                def execute(): Consequence[OperationResponse] = delegate.execute()
                override def afterCommitResponseC(response: OperationResponse): Consequence[OperationResponse] =
                  delegate.afterCommitResponseC(response).flatMap(responseC(_, core))
              }
            }
            case other => other
          }
      }})))
}
