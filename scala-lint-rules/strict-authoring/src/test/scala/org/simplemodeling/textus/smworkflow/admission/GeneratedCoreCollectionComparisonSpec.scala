package org.simplemodeling.textus.smworkflow.admission {

import scala.language.strictEquality
import scala.compiletime.testing.typeCheckErrors
import domain.value.{CountryCode, RegionCode}
import org.scalatest.GivenWhenThen
import org.scalatest.matchers.should.Matchers
import org.scalatest.wordspec.AnyWordSpec

/** Calls Core with generated values and generated Eq; call sites are authored.
  * @since   Nov. 21, 2026
  * @version Nov. 21, 2026
  * @author  ASAMI, Tomoharu
  */
final class GeneratedCoreCollectionComparisonSpec extends AnyWordSpec with Matchers with GivenWhenThen {
  "The Core consumer of Cozy-generated values" should {
    "consume each generated value's Eq while preserving value membership" in {
      Given("CountryCode and RegionCode generated by the selected normal CML library route")
      val countries = Vector(CountryCode("JP"), CountryCode("GB"))
      val regions = Vector(RegionCode("GB"))

      When("the main consumer calls containsEq without replacing the generated Eq instances")
      val country = GeneratedCoreCollectionComparisonExamples.containsCountry(countries, CountryCode("GB"))
      val region = GeneratedCoreCollectionComparisonExamples.containsRegion(regions, RegionCode("GB"))

      Then("matching same-type values are present and unmatched or empty values are absent")
      val _ = country shouldBe true
      val _ = region shouldBe true
      val _ = GeneratedCoreCollectionComparisonExamples.containsCountry(countries, CountryCode("US")) shouldBe false
      GeneratedCoreCollectionComparisonExamples.containsCountry(Vector.empty[CountryCode], CountryCode("GB")) shouldBe false
    }

    "close the precompiled contains type gap for a generated receiver" in {
      Given("different generated types with equal String representations and a common-parent Eq")

      When("the actual Core containsEq is used on the generated country receiver")
      val errors = typeCheckErrors("""
        import org.goldenport.util.TypeSafeCollections.*
        import domain.value.{CountryCode, RegionCode}
        given cats.Eq[Any] = cats.Eq.instance[Any]((_, _) => true)
        Vector(CountryCode("same")).typeSafe.containsEq(RegionCode("same"))
      """)

      Then("the mismatch is rejected at the containsEq call without granting cross-type comparison")
      val _ = errors should have size 1
      errors.foreach { error =>
        val _ = error.lineContent should include ("containsEq(RegionCode")
        val _ = error.message should include ("=:=" )
        val _ = error.message should include ("CountryCode")
        val _ = error.message should include ("RegionCode")
      }
    }
  }
}

}
